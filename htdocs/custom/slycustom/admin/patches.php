				$logs[] = '── sly24.0-'.$name.'.patch: '.($r['ok'] ? 'applied' : 'FAILED')."\n".$r['log'];
				if ($r['ok']) {
					slyPatchStatusCacheSet($name, 'applied');
				} else {
					$error++;
					break; // stop the chain on first failure: later patches may depend on it
				}
			} else {
				$logs[] = '── sly24.0-'.$name.'.patch: skipped (status: '.$st['status'].')';
			}
		}
	}

	if ($action == 'restorefrompack') {
		// Roll back a single patch by re-extracting its latest pack tar.gz.
		// Same end-state as the per-row Restore button (the row lands on
		// "not applied") — just sourced from one archive instead of
		// scattered files. Useful for cross-env rollback: download a pack
		// from prod, upload it to d-test, restore with one click.
		$pack = basename(GETPOST('pack', 'filename'));
		if (!preg_match('/^sly24\.0-[a-zA-Z0-9_.-]+\.tar\.gz$/', $pack)) {
			$logs[] = '── restorefrompack: refused pack name '.htmlspecialchars($pack);
			$error++;
		} else {
			slyPatchStatusCacheInvalidate();
			$r = slyPatchRestoreFromPack($pack);
			$logs[] = '── restorefrompack '.htmlspecialchars($pack).': '.($r['ok'] ? 'OK' : 'FAILED')."\n".$r['log'];
			if (!$r['ok']) {
				$error++;
			}
		}
	}

	if ($action == 'bundle_create') {
		// Manually snapshot the union of all patch targets — independent
		// from applyall. Useful before risky drift edits or just before
		// a doc walkthrough that needs a guaranteed restore point.
		$r = slyPatchMakeBundle();
