/**
 * Build the shell command fragments for status checking and applying.
 * Prefers git apply (atomic); falls back to the POSIX patch command.
 *
 * The git invocation carries `-c safe.directory=<DOL_DOCUMENT_ROOT>`:
 * when htdocs is a git checkout owned by a different user than the
 * php-fpm process (typical for /home/<user> deployments), git >= 2.35.2
 * refuses to run with "detected dubious ownership" — which made every
 * status check fail and every patch show "conflict". Older git versions
 * ignore the unknown config key, so this is safe everywhere.
 *
 * @return array{engine:string,check:string,checkrev:string,apply:string} Command templates with %s placeholders
 */
function slyPatchEngine()
{
	$git = trim((string) shell_exec('command -v git 2>/dev/null'));
	if ($git !== '') {
		$safe = '-c safe.directory='.escapeshellarg(str_replace('\\', '/', DOL_DOCUMENT_ROOT));
		// -p2 strips "a/htdocs/" — the patches are generated by
		// gen_sly24_patches.sh from the REPO ROOT (parent of htdocs), so
		// every header reads a/htdocs/<path>. We run inside
		// DOL_DOCUMENT_ROOT (= htdocs), hence two levels. -p1 made the
		// engine look for <htdocs>/htdocs/<path> (d-test2, 2026-09-22:
		// "error: htdocs/core/... No such file or directory").
		return array(
			'engine' => 'git apply',
			'check' => "git $safe apply --check -p2 --ignore-whitespace %s 2>&1",
			'checkrev' => "git $safe apply --check -R -p2 --ignore-whitespace %s 2>&1",
			'apply' => "git $safe apply -p2 --ignore-whitespace %s 2>&1",
		);
	}
	return array(
		'engine' => 'patch --batch --forward',
		'check' => 'patch --batch --dry-run --forward -p2 -i %s 2>&1',
		'checkrev' => 'patch --batch --dry-run -R -p2 -i %s 2>&1',
		'apply' => 'patch --batch --forward -p2 -i %s 2>&1',
	);
}

/**
 * Return a LF-normalised copy of a patch file. A patch saved on Windows
 * with CRLF endings cannot be applied by `git apply` on Linux: the CR
 * becomes part of the `+++ b/<file>` header and of every context line,
 * so BOTH the forward and the reverse dry-runs fail and the patch shows
 * "conflict" on a perfectly clean tree — the exact failure d-test and
 * d-test2 hit (2026-09-22, all 17 patches conflict on a pristine 24.0.1).
 *
 * When the file already has no CR the original path is returned and no
 * temp file is written. Otherwise a normalised copy is written under
 * DOL_DATA_ROOT/slycustom/patch-backups/.norm_<basename> (stable name,
 * idempotent overwrite, never cleaned up — a few dozen KB at worst).
 *
 * @param  string $patchfile Absolute path to the .patch file
 * @return string Path to feed the engine (original or normalised temp)
 */
function slyPatchNormalizePatchFile($patchfile)
{
	$content = @file_get_contents($patchfile);
	if ($content === false || strpos($content, "\r") === false) {
		return $patchfile;
	}
	$out = DOL_DATA_ROOT.'/slycustom/patch-backups/.norm_'.basename($patchfile);
	if (!slyPatchEnsureDir(dirname($out))) {
		return $patchfile; // cannot stage a normalised copy — engine will report
	}
	file_put_contents($out, str_replace("\r\n", "\n", $content));
	return $out;
}

/**
 * dol_mkdir() semantics: 0 = already exists, <0 = KO, >0 = created.
 * Code that treated its return as boolean (`!dol_mkdir($dir)`) misread
 * "already exists" (0) as failure — the first Create-bundle worked, and
 * every later pack/bundle build failed with a bogus "could not create
 * dir" (d-test2, 2026-09-22). This wrapper is truth-proof.
 *
 * @param  string $dir Absolute directory path
 * @return bool  True when $dir exists (pre-existing or just created)
 */
function slyPatchEnsureDir($dir)
{
	if (is_dir($dir)) {
		return true;
	}
	dol_mkdir($dir);
	return is_dir($dir);
}

/**
 * Detect the status of one patch: 'applied', 'notapplied', 'conflict' or 'missing'.
 *
 * @param  string $patchfile Absolute path to the .patch file
 * @param  array  $engine    Result of slyPatchEngine()
 * @return array  array('status'=>string, 'output'=>string)
 */
function slyPatchStatus($patchfile, $engine)
{
	if (!is_readable($patchfile)) {
		return array('status' => 'missing', 'output' => '');
	}
	// Feed the engine an LF-normalised copy when the stored patch has CRLF
	// endings — see slyPatchNormalizePatchFile().
	$patchfile = slyPatchNormalizePatchFile($patchfile);
	$cmd = 'cd '.escapeshellarg(DOL_DOCUMENT_ROOT).' && '.sprintf($engine['checkrev'], escapeshellarg($patchfile));
	exec($cmd, $out, $ret);
	if ($ret === 0) {
		return array('status' => 'applied', 'output' => '');
	}
	$cmd = 'cd '.escapeshellarg(DOL_DOCUMENT_ROOT).' && '.sprintf($engine['check'], escapeshellarg($patchfile));
	exec($cmd, $out2, $ret2);
	if ($ret2 === 0) {
		return array('status' => 'notapplied', 'output' => '');
	}
	return array('status' => 'conflict', 'output' => implode("\n", array_merge($out, $out2)));
}

/**
 * Session-cached status wrapper. A full sweep costs 2 exec() per patch
 * (reverse + forward dry-run) — 34 process spawns per PAGE VIEW on the
 * 17-patch tree, which throttled the d-test2 shared host to near-
 * unavailability during one-by-one applies (2026-09). Rows are cached for
 * 10 minutes; single-patch actions overwrite their own row with the
 * deterministic outcome; bulk actions drop the whole cache; the Rescan
 * button (?rescan=1) forces a fresh sweep.
 *
 * @param  string $name      Patch short name
 * @param  string $patchfile Absolute path to the .patch file
 * @param  array  $engine    Result of slyPatchEngine()
 * @param  bool   $force     Bypass the cache for this row
 * @return array  array('status'=>string, 'output'=>string)
 */
function slyPatchStatusCached($name, $patchfile, $engine, $force = false)
{
	if (!isset($_SESSION['slypatch_stcache']) || !is_array($_SESSION['slypatch_stcache'])) {
		$_SESSION['slypatch_stcache'] = array('t' => 0, 'st' => array());
	}
	$c = &$_SESSION['slypatch_stcache'];
	if (!$force && $c['t'] > 0 && (time() - $c['t']) < 600 && isset($c['st'][$name])) {
		return $c['st'][$name];
	}
	$st = slyPatchStatus($patchfile, $engine);
	$c['st'][$name] = $st;
	return $st;
}

/**
 * Start a status sweep: if the cached sweep is older than the TTL, reset it
 * so the rows computed during THIS sweep count as one fresh snapshot (the
 * per-row wrapper above only fills missing rows — without this reset a
 * stale cache would re-run every row on every view).
 *
 * @return void
 */
function slyPatchStatusSweepBegin()
{
	if (!isset($_SESSION['slypatch_stcache']) || !is_array($_SESSION['slypatch_stcache'])
		|| $_SESSION['slypatch_stcache']['t'] <= 0 || (time() - $_SESSION['slypatch_stcache']['t']) >= 600) {
		$_SESSION['slypatch_stcache'] = array('t' => time(), 'st' => array());
	}
}

/**
 * Overwrite one row with the deterministic outcome of a single-patch action
 * (applyone ok -> applied, restoreone ok -> notapplied). Does NOT touch the
 * sweep timestamp: other rows keep their original freshness window.
 *
 * @param  string $name   Patch short name
 * @param  string $status New status
 * @return void
 */
function slyPatchStatusCacheSet($name, $status)
{
	if (!isset($_SESSION['slypatch_stcache']) || !is_array($_SESSION['slypatch_stcache'])) {
		return;
	}
	$_SESSION['slypatch_stcache']['st'][$name] = array('status' => $status, 'output' => '');
}

/**
 * Drop the whole status cache — after bulk/tree-wide actions (applyall,
 * bundle restores, uploads) every row must be re-measured.
 *
 * @return void
 */
function slyPatchStatusCacheInvalidate()
{
	unset($_SESSION['slypatch_stcache']);
}

/**
 * Parse the list of target files from a unified diff.
 *
 * The sly24.0-*.patch headers are repo-root relative ("+++ b/htdocs/<path>")
 * because gen_sly24_patches.sh diffs from the repository root. Everything
 * downstream of this function (backup paths, packs, bundles, whitelist,
 * upload target list) works with DOL_DOCUMENT_ROOT-relative paths, so a
 * leading "htdocs/" segment is stripped when present. Keep in sync with
 * the engine's -p2 (strips "a/htdocs/") in slyPatchEngine().
 *
 * @param  string $patchfile Absolute path to the .patch file
 * @return array  List of paths relative to DOL_DOCUMENT_ROOT
 */
function slyPatchTargetFiles($patchfile)
{
	$targets = array();
	$fh = fopen($patchfile, 'r');
	if (!$fh) {
		return $targets;
	}
	while (($line = fgets($fh)) !== false) {
		if (preg_match('/^\+\+\+ b\/(.+)$/', rtrim($line, "\r\n"), $m)) {
			$rel = $m[1];
			if (strpos($rel, 'htdocs/') === 0) {
				$rel = substr($rel, strlen('htdocs/'));
			}
			$targets[] = $rel;
		}
	}
	fclose($fh);
	return $targets;
}

/**
 * Apply one patch. Deliberately minimal (user directive 2026-09-23):
 * back up only target files that have no pristine copy yet — never
 * re-backup — then run the engine apply. That's it. Rollback is the
 * per-patch pristine layer (Reset/Restore buttons copy it back), pack
 * creation is first-time-only, and patch QA happens entirely on the
 * development side before deployment — nothing diagnostic runs on the
 * server (user directive 2026-09-23).
 *
 * @param  string $name      Patch short name (whitelisted key)
 * @param  array  $engine    Result of slyPatchEngine()
 * @return array  array('ok'=>bool, 'log'=>string)
 */
function slyPatchApply($name, $engine)
{
	$patchfile = DOL_DOCUMENT_ROOT.'/custom/slycustom/patches/sly24.0-'.basename($name).'.patch';
	if (!is_readable($patchfile)) {
		return array('ok' => false, 'log' => 'Patch file not found: '.basename($patchfile));
	}

	$targets = slyPatchTargetFiles($patchfile);
	$perPatchDir = DOL_DATA_ROOT.'/slycustom/patch-backups/per-patch/'.basename($name);
	$copiedPerPatch = 0;
	$keptPerPatch = 0;
	foreach ($targets as $rel) {
		$src = DOL_DOCUMENT_ROOT.'/'.$rel;
		if (!is_file($src)) {
			continue; // new file created by the patch, nothing to back up
		}
		$dstPerPatch = $perPatchDir.'/'.$rel;
		if (is_file($dstPerPatch)) {
			$keptPerPatch++; // pristine copy already exists — never re-backup
			continue;
		}
		dol_mkdir(dirname($dstPerPatch));
		if (copy($src, $dstPerPatch)) {
			$copiedPerPatch++;
		}
	}

	// Pack from the pristine per-patch layer, first time only (an existing
	// pack is kept — content is deterministic).
	$packLog = slyPatchMakePack($name, $targets, $perPatchDir);
	$log = $packLog['log'];

	$cmd = 'cd '.escapeshellarg(DOL_DOCUMENT_ROOT).' && '.sprintf($engine['apply'], escapeshellarg(slyPatchNormalizePatchFile($patchfile)));
	exec($cmd, $out, $ret);
	$log .= "\n".($ret === 0 ? 'OK' : 'FAILED (exit '.$ret.')')."\n".implode("\n", $out);
	$log .= "\nPer-patch backup: $perPatchDir ($copiedPerPatch new, $keptPerPatch kept)";

	return array('ok' => ($ret === 0), 'log' => $log);
}

/**
 * Best-effort recursive removal of a staging directory. Used only for the
 * upload-bundle temp dir; failures are silently ignored (the dir lives
 * under documents/ where a leftover is harmless and visible to the admin).
 *
 * @param  string $dir Absolute path to remove
 * @return void
 */
function slyPatchRmDirTree($dir)
{
	if (!is_dir($dir)) {
		return;
	}
	$rii = new RecursiveIteratorIterator(
		new RecursiveDirectoryIterator($dir, FilesystemIterator::SKIP_DOTS),
		RecursiveIteratorIterator::CHILD_FIRST
	);
	foreach ($rii as $f) {
		$f->isDir() ? @rmdir($f->getPathname()) : @unlink($f->getPathname());
	}
	@rmdir($dir);
}

/**
 * Restore every file in a patch's per-patch backup directory back to its
 * original htdocs-relative location. Used by the per-patch Reset button —
 * copies are local (no git, no network) and complete in well under a second.
 *
 * @param  string $name Patch short name (whitelisted key, basename-safe)
 * @return array        array('ok'=>bool, 'log'=>string, 'restored'=>int,
 *                          'missing'=>bool, 'failList'=>array<relPath=>reason>)
 */
function slyPatchRestoreFilesFromBackup($name)
{
	$perPatchDir = DOL_DATA_ROOT.'/slycustom/patch-backups/per-patch/'.basename($name);
	if (!is_dir($perPatchDir)) {
		return array(
			'ok'       => false,
			'log'      => 'No per-patch backup at '.$perPatchDir.' (this patch was never applied, or its backup was deleted).',
			'restored' => 0,
			'missing'  => true,
			'failList' => array(),
		);
	}
	$restored = 0;
	$failList = array();
	$entries = new RecursiveIteratorIterator(
		new RecursiveDirectoryIterator($perPatchDir, FilesystemIterator::SKIP_DOTS),
		RecursiveIteratorIterator::SELF_FIRST
	);
	foreach ($entries as $info) {
		if ($info->isDir()) {
			continue;
		}
		$rel = substr(str_replace('\\', '/', $info->getPathname()), strlen(str_replace('\\', '/', $perPatchDir)) + 1);
		if ($rel === '' || strpos($rel, '..') !== false) {
			// belt-and-braces: refuse anything that smells like a traversal
			$failList[$rel] = 'unsafe relative path';
			continue;
		}
		$dst = DOL_DOCUMENT_ROOT.'/'.$rel;
		if (!is_dir(dirname($dst))) {
			dol_mkdir(dirname($dst));
		}
		if (@copy($info->getPathname(), $dst)) {
			$restored++;
		} else {
			$failList[$rel] = 'copy failed';
		}
	}
	$lines = array("Restored $restored file(s) from $perPatchDir");
	if ($failList !== array()) {
		$lines[] = 'Failed: '.implode(', ', array_map(function ($k, $v) {
			return "$k ($v)";
		}, array_keys($failList), array_values($failList)));
	}
	return array('ok' => $failList === array(), 'log' => implode("\n", $lines), 'restored' => $restored, 'missing' => false, 'failList' => $failList);
}

/**
 * Extract a .tar.gz archive into $targetDir using the system tar. Returns
 * the list of relative entries (no `..` / no absolute paths) so the caller
 * can whitelist them before doing anything destructive. The archive is NOT
 * deleted by this helper — caller owns the temp file lifecycle.
 *
 * Strict safety net: entries are listed in verbose mode (`tar -tvzf`) so
 * link/device entries are visible and refused BEFORE extraction — a tar
 * symlink followed by a path through it would otherwise escape $targetDir.
 * Every entry must be a relative file path without `..` segments. The
 * tarball is unpacked with `tar -xzf` from inside $targetDir.
 *
 * @param  string $archivePath Absolute path to a .tar.gz file
 * @param  string $targetDir   Absolute path to an existing writable dir
 * @return array  array('ok'=>bool,'log'=>string,'entries'=>array)
 */
function slyPatchExtractTarGz($archivePath, $targetDir)
{
	if (!is_readable($archivePath)) {
		return array('ok' => false, 'log' => 'Archive not readable: '.$archivePath, 'entries' => array());
	}
	if (!is_dir($targetDir)) {
		return array('ok' => false, 'log' => 'Target dir not found: '.$targetDir, 'entries' => array());
	}
	// Enumerate entries first so we can refuse unsafe paths BEFORE extracting.
	// Verbose listing: first field is the mode string, whose type character
	// ('l' = symlink, 'h' = hardlink, block/char device...) we refuse.
	$cmd = 'tar -tvzf '.escapeshellarg($archivePath).' 2>&1';
	exec($cmd, $listOut, $listRet);
	if ($listRet !== 0) {
		return array('ok' => false, 'log' => 'tar -tvzf failed: '.implode("\n", $listOut), 'entries' => array());
	}
	$safe = array();
	foreach ($listOut as $raw) {
		$raw = rtrim($raw, "\r\n");
		if ($raw === '') continue;
		if (!preg_match('/^([-dlhcbp])[rwxstST-]+\s/', $raw, $typeM)) {
			return array('ok' => false, 'log' => 'Archive entry has unparseable type: '.htmlspecialchars($raw, ENT_QUOTES, 'UTF-8'), 'entries' => array());
		}
		if ($typeM[1] !== '-') {
			return array('ok' => false, 'log' => 'Archive contains a non-regular entry (link/device): '.htmlspecialchars($raw, ENT_QUOTES, 'UTF-8'), 'entries' => array());
		}
		// Path = last whitespace-separated token (works with user/group cols).
		$rel = trim(substr($raw, strrpos($raw, ' ')));
		$rel = ltrim($rel, '/');
		if ($rel === '' || strpos($rel, '..') !== false) {
			return array('ok' => false, 'log' => 'Archive contains unsafe path: '.htmlspecialchars($raw, ENT_QUOTES, 'UTF-8'), 'entries' => array());
		}
		$safe[] = $rel;
	}
	$cmd = 'cd '.escapeshellarg($targetDir).' && tar -xzf '.escapeshellarg($archivePath).' 2>&1';
	exec($cmd, $exOut, $exRet);
	if ($exRet !== 0) {
		return array('ok' => false, 'log' => 'tar -xzf failed: '.implode("\n", $exOut), 'entries' => $safe);
	}
	return array('ok' => true, 'log' => 'Extracted '.count($safe).' entries', 'entries' => $safe);
}

/**
 * Build an in-memory reverse map: every htdocs-relative path -> list of
 * patch short names whose `+++ b/<path>` headers mention it. Used by the
 * upload-bundle path to know which per-patch/<name>/ dir each uploaded
 * file belongs to (so the upload not only restores DOL_DOCUMENT_ROOT but
 * also seeds the per-patch backup layer that future Reset calls rely on).
 *
 * @return array<string, array<string>> file => [patch names]
 */
function slyPatchFileToPatchesMap()
{
	global $PATCHES;
	$map = array();
	foreach (array_keys($PATCHES) as $name) {
		$patchfile = DOL_DOCUMENT_ROOT.'/custom/slycustom/patches/sly24.0-'.$name.'.patch';
		if (!is_readable($patchfile)) continue;
		foreach (slyPatchTargetFiles($patchfile) as $rel) {
			if (!is_string($rel) || $rel === '' || strpos($rel, '..') !== false) continue;
			if (!isset($map[$rel])) $map[$rel] = array();
			$map[$rel][] = $name;
		}
	}
	return $map;
}

/**
 * Ingest an operator-uploaded clean 24.0.1 bundle tar.gz into two places:
 *   (a) DOL_DOCUMENT_ROOT  — restore every target file to its pristine
 *       upstream contents (overwrites the dirty tree currently sitting in
 *       htdocs/ — exactly what we need when every patch reports Conflict
 *       because the tree has drifted away from 24.0.1);
 *   (b) documents/slycustom/patch-backups/per-patch/<name>/ — seed a
 *       per-patch backup for every patch that touches the file, so the
 *       next Reset / Restore round can run as a pure local `cp` without
 *       ever needing this upload path again.
 *
 * Whitelist: only files in slyPatchAllTargetFiles() are accepted. Anything
 * else in the archive is silently dropped (a pristine 24.0.1 bundle should
 * not carry anything else, and this protects the operator from typos).
 *
 * Caller responsibility: the archive has already been whitelisted by
 * basename, size-capped, and is on a trusted local temp path. This helper
 * does not move or delete $archivePath.
 *
 * @param  string $archivePath Absolute path to the uploaded .tar.gz
 * @return array  array('ok'=>bool,'log'=>string,'restored'=>int,'seeded'=>array)
 */
function slyPatchIngestUploadedBundle($archivePath)
{
	// Single source of truth: the file->patches reverse map. Its keys are
	// exactly the whitelisted htdocs-relative paths, so we never risk an
	// isset() mismatch between two independently-built whitelists.
	$fileToPatches = slyPatchFileToPatchesMap();
	if ($fileToPatches === array()) {
		return array('ok' => false, 'log' => 'No patch target files known — refusing upload.', 'restored' => 0, 'seeded' => array());
	}
	$tempDir = DOL_DATA_ROOT.'/slycustom/patch-backups/.upload_'.bin2hex(random_bytes(4));
	if (!slyPatchEnsureDir($tempDir)) {
		return array('ok' => false, 'log' => 'Could not create temp dir '.$tempDir, 'restored' => 0, 'seeded' => array());
	}
	$ex = slyPatchExtractTarGz($archivePath, $tempDir);
	if (!$ex['ok']) {
		slyPatchRmDirTree($tempDir);
		return array('ok' => false, 'log' => 'Extraction failed: '.$ex['log'], 'restored' => 0, 'seeded' => array());
	}
	$restored = 0;
	$seeded = array();
	$reseeded = 0;
	$failed = array();
	foreach (array_keys($fileToPatches) as $rel) {
		$src = $tempDir.'/'.$rel;
		if (!is_file($src)) {
			// Tolerate bundles packed from the REPO root (htdocs/<path> layout).
			$alt = $tempDir.'/htdocs/'.$rel;
			if (is_file($alt)) {
				$src = $alt;
			} else {
				// File absent from the uploaded archive — fine, the operator
				// may have packed only a subset; skip silently.
				continue;
			}
		}
		// (a) Restore into DOL_DOCUMENT_ROOT.
		$dst = DOL_DOCUMENT_ROOT.'/'.$rel;
		if (!is_dir(dirname($dst))) {
			dol_mkdir(dirname($dst));
		}
		if (!@copy($src, $dst)) {
			$failed[] = "$rel (copy to DOL_DOCUMENT_ROOT failed)";
			continue;
		}
		$restored++;
		// (b) (Re)seed per-patch backup for every patch that touches this file.
		// The upload is an explicit reset-to-pristine operation (the confirm
		// dialog asserts a clean 24.0.1 source tree), so existing backup files
		// are OVERWRITTEN — a previously poisoned backup layer (e.g. seeded
		// from a non-pristine bundle) is exactly what this must displace.
		foreach (($fileToPatches[$rel] ?? array()) as $name) {
			$perPatchFile = DOL_DATA_ROOT.'/slycustom/patch-backups/per-patch/'.basename($name).'/'.$rel;
			$existed = is_file($perPatchFile);
			if ($existed && !is_writable($perPatchFile)) {
				$failed[] = "$rel (per-patch backup for $name not writable)";
				continue;
			}
			if (!is_dir(dirname($perPatchFile))) {
				dol_mkdir(dirname($perPatchFile));
			}
			if (@copy($src, $perPatchFile)) {
				if ($existed) {
					$reseeded++;
				} else {
					if (!isset($seeded[$name])) $seeded[$name] = 0;
					$seeded[$name]++;
				}
			}
		}
	}
	slyPatchRmDirTree($tempDir);

	$targetTotal = count($fileToPatches);
	$absent = $targetTotal - $restored - count($failed);
	$lines = array();
	$lines[] = "Restored $restored file(s) from uploaded bundle into DOL_DOCUMENT_ROOT";
	$lines[] = "Coverage: $restored/$targetTotal target file(s) present in archive".($absent > 0 ? "; $absent absent (operator may have packed a subset)" : ' — complete');
	if (count($seeded) > 0) {
		$pairs = array();
		foreach ($seeded as $n => $c) $pairs[] = "$n ($c file(s))";
		$lines[] = 'Seeded per-patch backup for '.count($seeded).' patch(es): '.implode(', ', $pairs);
	}
	if ($reseeded > 0) {
		$lines[] = "Re-seeded (overwritten) $reseeded existing per-patch backup file(s) with bundle content";
	}
	if (count($seeded) === 0 && $reseeded === 0) {
		$lines[] = 'No per-patch backup was seeded (no overlap with patch targets)';
	}
	if ($failed !== array()) {
		$lines[] = 'Failures: '.implode('; ', $failed);
	}
	return array(
		'ok' => $failed === array(),
		'log' => implode("\n", $lines),
		'restored' => $restored,
		'seeded' => $seeded,
		'reseeded' => $reseeded,
	);
}

