if (in_array($action, array('applyall', 'applyone', 'restoreone', 'resetone', 'resetapplyall_smart', 'restorefrompack', 'bundle_create', 'restore_bundle', 'upload_bundle')) && $versionOk) {
	// main.inc.php rejects a wrong token automatically; a missing one on POST we reject here.
	if ($_SERVER['REQUEST_METHOD'] == 'POST' && !GETPOSTISSET('token')) {
		accessforbidden();
		exit;
	}
	$engine = slyPatchEngine();

	// Local-only reset path: triggered when one or more patches report
	// "Conflict". We restore the conflict-touched files using each patch's
	// own per-patch backup (a pristine pre-patch copy of every file that
	// patch touched, captured the first time slyPatchApply ran). No git,
	// no network, no archive upload — only local files under
	// documents/slycustom/patch-backups/per-patch/<name>/. Every other
	// file in DOL_DOCUMENT_ROOT stays untouched, so this is safe to run
	// on a partially-customised deployment.
	//
	// On success, falls through to the apply-all chain so the freshly
	// re-baselined tree ends with all SLY customisations reapplied.
	if ($action == 'resetapplyall_smart') {
		// Fresh sweep: the conflict set decides which backups get restored.
		slyPatchStatusSweepBegin();
		$conflictPatches = array();
		foreach ($PATCHES as $name => $_) {
			$patchfile = DOL_DOCUMENT_ROOT.'/custom/slycustom/patches/sly24.0-'.$name.'.patch';
			$st = slyPatchStatusCached($name, $patchfile, $engine);
			if ($st['status'] == 'conflict') {
				$conflictPatches[] = $name;
			}
		}

		if ($conflictPatches === array()) {
			$logs[] = '── Smart reset: no conflict patches detected; falling through to plain apply-all.';
		} else {
			$logs[] = '── Conflict patches: '.implode(', ', $conflictPatches);
			$logs[] = '── Source: per-patch backup (documents/slycustom/patch-backups/per-patch/<name>/) — pure local cp, no network / no git.';
			$smartOk = true;
			$missing = array();
			foreach ($conflictPatches as $name) {
				$r = slyPatchRestoreFilesFromBackup($name);
				$logs[] = '──   '.$name.': '.($r['ok'] ? 'OK ('.$r['restored'].' file(s))' : 'FAILED')."\n".$r['log'];
				if (!$r['ok']) {
					$smartOk = false;
					if (!empty($r['missing'])) {
						$missing[] = $name;
					}
				}
			}
			if (!$smartOk) {
				if ($missing !== array()) {
					setEventMessages($langs->trans('SlyPatchResetLocalFailed', implode(', ', $missing)), null, 'errors');
				} else {
					setEventMessages($langs->trans('SlyPatchResetAllFailed'), null, 'errors');
				}
				header('Location: '.$_SERVER['PHP_SELF'].'?message='.urlencode('PatchApplyError'));
				exit;
			}
		}
		// Walk the 17-patch chain over the freshly re-baselined tree. The
		// restores above changed files — the sweep rows are stale now.
		slyPatchStatusCacheInvalidate();
		$action = 'applyall';
	}

	if ($action == 'applyone') {
		if (!array_key_exists($applyname, $PATCHES)) {
			accessforbidden();
			exit;
		}
		// Force a live measurement for the apply decision: cached rows can be
		// minutes old and the operator may have changed files out-of-band.
		$st = slyPatchStatusCached($applyname, DOL_DOCUMENT_ROOT.'/custom/slycustom/patches/sly24.0-'.$applyname.'.patch', $engine, true);
		if ($st['status'] == 'notapplied') {
			$r = slyPatchApply($applyname, $engine);
			$logs[] = '── sly24.0-'.$applyname.'.patch: '.($r['ok'] ? 'applied' : 'FAILED')."\n".$r['log'];
			if ($r['ok']) {
				slyPatchStatusCacheSet($applyname, 'applied');
			} else {
				$error++;
			}
		} else {
			$logs[] = '── sly24.0-'.$applyname.'.patch: skipped (status: '.$st['status'].')';
		}
	}

	if ($action == 'restoreone') {
		// Roll back a single patch: copy every per-patch backup file back to its
		// htdocs-relative location and stop there (no re-apply). After this the
		// patch is in the "not applied" state — the file tree matches the
		// pre-patch contents, so a forward `git apply --check` succeeds.
		if (!array_key_exists($applyname, $PATCHES)) {
			accessforbidden();
			exit;
		}
		$r = slyPatchRestoreFilesFromBackup($applyname);
		$logs[] = '── sly24.0-'.$applyname.'.patch: restore from backup '.($r['ok'] ? 'OK' : 'FAILED')."\n".$r['log'];
		if ($r['ok']) {
			slyPatchStatusCacheSet($applyname, 'notapplied');
		} else {
			$error++;
		}
	}

	if ($action == 'resetone') {
		// Per-patch Reset: copy the patch's pre-patch backup back to
		// DOL_DOCUMENT_ROOT, then re-apply the patch so the row lands
		// back on the "applied" badge (matching what a fresh install
		// would look like). The per-patch backup is captured the first
		// time slyPatchApply runs and never overwritten afterwards, so
		// a Reset is always a local `cp` away — no git, no network,
		// no archive.
		//
		// If the per-patch backup is missing (the patch was applied by
		// an older slycustom release that didn't have this backup layer,
		// or the backup was wiped), Reset refuses with a clear recovery
		// message instead of falling back to git / auto-download — the
		// tool's only rollback source is the local pre-backup.
		if (!array_key_exists($applyname, $PATCHES)) {
			accessforbidden();
			exit;
		}
		$r = slyPatchRestoreFilesFromBackup($applyname);
		$logs[] = '── sly24.0-'.$applyname.'.patch: restore from per-patch backup '.($r['ok'] ? 'OK' : 'FAILED').' ('.$r['restored'].' file(s)'.")\n".$r['log'];
		if (!$r['ok']) {
			if (!empty($r['missing'])) {
				setEventMessages($langs->trans('SlyPatchResetLocalFailed', $applyname), null, 'errors');
			}
			$error++;
		}
		// Re-apply so the row lands on the "applied" badge (post-restore the
		// file tree is in pre-patch state; forward `git apply` brings it back
		// to the patched state, which is the operator's intent).
		$st2 = slyPatchStatus(DOL_DOCUMENT_ROOT.'/custom/slycustom/patches/sly24.0-'.$applyname.'.patch', $engine);
		if ($st2['status'] == 'notapplied') {
			$ra = slyPatchApply($applyname, $engine);
			$logs[] = '── sly24.0-'.$applyname.'.patch: re-apply '.($ra['ok'] ? 'OK' : 'FAILED')."\n".$ra['log'];
			if (!$ra['ok']) {
				$error++;
			}
		} else {
			$logs[] = '── sly24.0-'.$applyname.'.patch: re-apply skipped (status: '.$st2['status'].')';
		}
		// Branchy outcomes (restore ok / re-apply ok / skipped) — drop the
		// cache and let the next view re-measure instead of guessing.
		slyPatchStatusCacheInvalidate();
	}

	if ($action == 'applyall') {
		// Pre-applyall snapshot: bundle (every patch target, deduped) into
		// one tar.gz so the operator can one-shot roll back the entire
		// patch family, regardless of how many patches overlap on the
		// same file. Failure here is logged but does NOT block the applyall
		// chain — the per-patch packs below remain the source of truth.
		$bundleLog = slyPatchMakeBundle();
		$logs[] = '── Pre-applyall bundle: '.($bundleLog['ok'] ? 'OK' : 'FAILED')."\n".$bundleLog['log'];

		// One shared sweep for the whole chain (17 patches × 2 dry-runs would
		// otherwise be paid again by the post-redirect view).
		slyPatchStatusSweepBegin();
		foreach (array_keys($PATCHES) as $name) {
			$patchfile = DOL_DOCUMENT_ROOT.'/custom/slycustom/patches/sly24.0-'.$name.'.patch';
			$st = slyPatchStatusCached($name, $patchfile, $engine);
