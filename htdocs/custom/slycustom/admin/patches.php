			$logs[] = '── restore_bundle '.htmlspecialchars($latestBundle).': '.($r['ok'] ? 'OK' : 'FAILED')."\n".$r['log'];
			if (!$r['ok']) {
				$error++;
			}
		}
	}

	if ($action == 'upload_bundle') {
		// Recovery path for the deadlock where every patch is in Conflict
		// AND the per-patch backup layer is missing (applied by an older
		// slycustom release that lacked this layer, or backups were wiped).
		// The operator builds a clean 24.0.1 tar.gz off-host from a pristine
		// git clone + the target-list downloaded via downloadtargetlist,
		// then uploads it here. The tool whitelists by basename + size,
		// extracts to a temp dir, copies each file into DOL_DOCUMENT_ROOT,
		// and seeds the per-patch backup layer so future Reset calls are a
		// pure local `cp` away. No network, no git — the operator is the
		// only source of bytes, exactly as for every other rollback path.
		//
		// Size cap is 16MB: real bundles are 5-10MB, and a cap at the
		// post_max_size limit (32M on d-test) would be rejected by PHP at
		// the protocol layer with $_FILES empty — a misleading "no file"
		// error instead of our own clear message.
		$uploadErr = '';
		$uploadName = '';
		if (!isset($_FILES['bundle'])) {
			$uploadErr = 'no file in upload field';
		} elseif (!is_array($_FILES['bundle']) || !isset($_FILES['bundle']['error'])) {
			$uploadErr = 'malformed upload payload';
		} elseif ($_FILES['bundle']['error'] !== UPLOAD_ERR_OK) {
			$uploadErr = 'upload error code '.(int) $_FILES['bundle']['error'];
		} else {
			$uploadName = basename((string) $_FILES['bundle']['name']);
			$uploadSize = (int) $_FILES['bundle']['size'];
			if ($uploadSize <= 0 || $uploadSize > 16 * 1024 * 1024) {
				$uploadErr = 'size out of range (1..16MB)';
			} elseif (!preg_match('/^sly24\.0-[a-zA-Z0-9_.-]+\.tar\.gz$/', $uploadName)) {
				$uploadErr = 'basename not whitelisted: '.$uploadName;
			} else {
				$tmp = (string) $_FILES['bundle']['tmp_name'];
				if (!is_readable($tmp)) {
					$uploadErr = 'temp file not readable';
				} else {
					$r = slyPatchIngestUploadedBundle($tmp);
					$logs[] = '── upload_bundle '.htmlspecialchars($uploadName).': '.($r['ok'] ? 'OK' : 'FAILED')."\n".$r['log'];
					if ($r['ok']) {
						slyPatchStatusCacheInvalidate();
						if (!empty($r['reseeded'])) {
							setEventMessages($langs->trans('SlyPatchUploadBundleOkReseeded', (string) $r['restored'], (string) $r['reseeded']), null);
						} else {
							setEventMessages($langs->trans('SlyPatchUploadBundleOk', $r['restored'], count($r['seeded'])), null);
						}
					} else {
						setEventMessages($langs->trans('SlyPatchUploadBundleFailed', $r['log']), null, 'errors');
						$error++;
					}
				}
			}
		}
		if ($uploadErr !== '') {
			setEventMessages($langs->trans('SlyPatchUploadBundleFailed', $uploadErr), null, 'errors');
			$logs[] = '── upload_bundle refused: '.htmlspecialchars($uploadErr);
			$error++;
		}
	}

	// Persist the detailed engine log across the redirect below so the
	// operator actually sees per-patch results, backup paths and failure
	// output (setEventMessages only carries the short banner).
	if ($logs !== array()) {
		$_SESSION['slypatch_lastlogs'] = implode("\n\n", $logs);
	}

	// Same-page redirect pattern to clear the action from the URL.
	header('Location: '.$_SERVER['PHP_SELF'].($error ? '?message='.urlencode('PatchApplyError') : '?message='.urlencode('PatchApplyDone')));
	exit;
}

