/**
 * Pack every pre-patch target file of one patch into a single tar.gz archive
 * under DOL_DATA_ROOT/slycustom/patch-backups/packs/. Complementary to the
 * per-file per-patch backup: the pack is one portable artifact holding all
 * files a given patch would touch, in pristine (pre-patch) form, so it can
 * be downloaded, archived, or fed back into slyPatchRestoreFromPack on a
 * different host.
 *
 * Pack failure is reported but does NOT fail the surrounding slyPatchApply
 * call — the per-file backup is independent and already covers rollback.
 *
 * @param  string $name    Patch short name (basename-safe whitelist key)
 * @param  array  $targets Pre-patch file list (htdocs-relative paths)
 * @return array  array('ok'=>bool,'log'=>string)
 */
function slyPatchMakePack($name, $targets, $srcRoot = '')
{
	$packDir = DOL_DATA_ROOT.'/slycustom/patch-backups/packs';
	if (!slyPatchEnsureDir($packDir)) {
		return array('ok' => false, 'log' => 'Pack: could not create dir '.$packDir);
	}
	// Deterministic content (pristine files never change): when a pack for
	// this patch already exists, keep it instead of spawning another tar —
	// applyall would otherwise pay 17 tar invocations for nothing.
	$existing = slyPatchListPacks($name);
	if ($existing !== array()) {
		$newest = array_key_first($existing);
		return array('ok' => true, 'log' => 'Pack: existing '.basename($newest).' kept (pristine content is deterministic)');
	}
	if ($srcRoot === '') {
		$srcRoot = DOL_DOCUMENT_ROOT;
	}
	$lines = array();
	foreach ($targets as $rel) {
		$rel = ltrim($rel, '/');
		if ($rel === '' || strpos($rel, '..') !== false) continue;
		if (is_file($srcRoot.'/'.$rel)) {
			$lines[] = $rel;
		}
	}
	if ($lines === array()) {
		return array('ok' => true, 'log' => 'Pack: nothing to pack (patch only creates new files)');
	}
	$listFile = $packDir.'/.list_'.basename($name).'_'.bin2hex(random_bytes(4));
	file_put_contents($listFile, implode("\n", $lines));
	$packFile = $packDir.'/sly24.0-'.basename($name).'_'.dol_print_date(dol_now(), 'dayhourlog').'.tar.gz';
	$cmd = 'cd '.escapeshellarg($srcRoot).' && tar -czf '.escapeshellarg($packFile).' --no-recursion -T '.escapeshellarg($listFile).' 2>&1';
	exec($cmd, $tarOut, $tarRet);
	@unlink($listFile);
	if ($tarRet !== 0) {
		@unlink($packFile);
		return array('ok' => false, 'log' => 'Pack FAILED: '.implode("\n", $tarOut));
	}
	$size = @filesize($packFile);
	return array(
		'ok' => true,
		'log' => 'Pack: '.$packFile.' ('.($size !== false ? $size : '?').' bytes, '.count($lines).' file(s))'
	);
}

/**
 * List every pack archive present for a given patch, newest first.
 *
 * @param  string $name Patch short name
 * @return array  Map: filename => filemtime (unix seconds), newest first
 */
function slyPatchListPacks($name)
{
	$packDir = DOL_DATA_ROOT.'/slycustom/patch-backups/packs';
	$out = array();
	if (!is_dir($packDir)) return $out;
	$prefix = 'sly24.0-'.basename($name).'_';
	$suffix = '.tar.gz';
	$dh = @opendir($packDir);
	if ($dh === false) return $out;
	while (($f = readdir($dh)) !== false) {
		if (substr($f, 0, strlen($prefix)) === $prefix && substr($f, -strlen($suffix)) === $suffix) {
			$full = $packDir.'/'.$f;
			if (is_file($full)) {
				$out[$f] = filemtime($full);
			}
		}
	}
	closedir($dh);
	arsort($out);
	return $out;
}

/**
 * Restore every file in one pack archive back into DOL_DOCUMENT_ROOT.
 * Security model identical to the upload path: (1) basename restricted to
 * sly24.0-<name>_<ts>.tar.gz, (2) verbose listing parsed to refuse symlink
 * / hardlink / device entries, (3) traversal check, (4) every entry must be
 * in the union of all patch target files — an archive planted in packs/
 * cannot touch anything outside the patch tool's own blast radius.
 *
 * @param  string $packFilename Basename only; whitelist regex restricts
 *                              it to sly24.0-<name>_<ts>.tar.gz
 * @return array  array('ok'=>bool,'log'=>string)
 */
function slyPatchRestoreFromPack($packFilename)
{
	$packFilename = basename($packFilename);
	if (!preg_match('/^sly24\.0-[a-zA-Z0-9_.-]+\.tar\.gz$/', $packFilename)) {
		return array('ok' => false, 'log' => 'Refused: pack name format mismatch: '.htmlspecialchars($packFilename));
	}
	$full = DOL_DATA_ROOT.'/slycustom/patch-backups/packs/'.$packFilename;
	if (!is_readable($full)) {
		return array('ok' => false, 'log' => 'Pack not found: '.$packFilename);
	}
	// Verbose listing: type character first on each line ('-' = regular
	// file; 'l'/'h' links and devices are refused before any extraction).
	$listCmd = 'tar -tvzf '.escapeshellarg($full).' 2>&1';
	exec($listCmd, $listOut, $listRet);
	if ($listRet !== 0) {
		return array('ok' => false, 'log' => 'tar list failed: '.implode("\n", $listOut));
	}
	$whitelist = array_flip(slyPatchAllTargetFiles());
	$fileCount = 0;
	foreach ($listOut as $entry) {
		$entry = rtrim($entry, "\r\n");
		if ($entry === '') continue;
		if (!preg_match('/^([-dlhcbp])[rwxstST-]+\s/', $entry, $typeM)) {
			return array('ok' => false, 'log' => 'Refused: unparseable archive entry: '.htmlspecialchars($entry));
		}
		if ($typeM[1] !== '-') {
			return array('ok' => false, 'log' => 'Refused: archive contains a non-regular entry (link/device): '.htmlspecialchars($entry));
		}
		$rel = ltrim(trim(substr($entry, strrpos($entry, ' '))), '/');
		if ($rel === '' || substr($rel, -1) === '/') continue;
		if (strpos($rel, '..') !== false) {
			return array('ok' => false, 'log' => 'Refused: archive contains path-traversal entry: '.htmlspecialchars($entry));
		}
		if (!isset($whitelist[$rel])) {
			return array('ok' => false, 'log' => 'Refused: archive entry outside the patch-target whitelist: '.htmlspecialchars($rel));
		}
		$fileCount++;
	}
	if ($fileCount === 0) {
		return array('ok' => true, 'log' => 'Pack is empty (no files to restore)');
	}
	$cmd = 'cd '.escapeshellarg(DOL_DOCUMENT_ROOT).' && tar -xzf '.escapeshellarg($full).' 2>&1';
	exec($cmd, $out, $ret);
	return array(
		'ok' => $ret === 0,
		'log' => 'Extracted '.$fileCount." file(s) from $packFilename to DOL_DOCUMENT_ROOT\n".implode("\n", $out)
	);
}

/**
 * Union the file targets (htdocs-relative) of every patch in the series.
 * Used to build the cross-patch bundle. When two patches touch the same
 * htdocs-relative path (e.g. core + remx + other-modules all edit
 * htdocs/main.inc.php), the union collapses the overlap so the bundle
 * captures each file exactly once.
 *
 * @return array Sorted list of htdocs-relative paths, deduped.
 */
function slyPatchAllTargetFiles()
{
	global $PATCHES;
	$all = array();
	foreach (array_keys($PATCHES) as $name) {
		$patchfile = DOL_DOCUMENT_ROOT.'/custom/slycustom/patches/sly24.0-'.$name.'.patch';
		if (!is_readable($patchfile)) continue;
		foreach (slyPatchTargetFiles($patchfile) as $f) {
			if (is_string($f) && $f !== '' && strpos($f, '..') === false) {
				$all[$f] = true;
			}
		}
	}
	ksort($all);
	return array_keys($all);
}

/**
 * Pack every file across ALL sly24.0-*.patch target paths (deduped) into
 * a SINGLE tar.gz. The bundle is the safe rollback when per-patch packs
 * would be wrong: when two patches touch the same file, each per-patch
 * pack captures the post-prior-patch state — but the union bundle gives
 * one consistent snapshot captured BEFORE the applyall chain begins.
 *
 * Auto-invoked at the start of every applyall; manually triggerable via
 * action=bundle_create. Older bundles are kept (manual GC is the
 * operator's call — we never delete backups automatically).
 *
 * @return array array('ok'=>bool,'log'=>string,'packfile'=>string,'count'=>int)
 */
function slyPatchMakeBundle()
{
	$targets = slyPatchAllTargetFiles();
	if ($targets === array()) {
		return array('ok' => true, 'log' => 'Bundle: union of all patch targets is empty', 'packfile' => '', 'count' => 0);
	}
	$packDir = DOL_DATA_ROOT.'/slycustom/patch-backups/packs';
	if (!slyPatchEnsureDir($packDir)) {
		return array('ok' => false, 'log' => 'Bundle: could not create dir '.$packDir, 'packfile' => '', 'count' => 0);
	}
	$lines = array();
	foreach ($targets as $rel) {
		$rel = ltrim($rel, '/');
		if ($rel === '' || strpos($rel, '..') !== false) continue;
		if (is_file(DOL_DOCUMENT_ROOT.'/'.$rel)) {
			$lines[] = $rel;
		}
	}
	if ($lines === array()) {
		return array('ok' => true, 'log' => 'Bundle: every unioned target is a new file (nothing to pack)', 'packfile' => '', 'count' => 0);
	}
	$listFile = $packDir.'/.list_bundle_'.bin2hex(random_bytes(4));
	file_put_contents($listFile, implode("\n", $lines));
	$packFile = $packDir.'/sly24.0-bundle_'.dol_print_date(dol_now(), 'dayhourlog').'.tar.gz';
	$cmd = 'cd '.escapeshellarg(DOL_DOCUMENT_ROOT).' && tar -czf '.escapeshellarg($packFile).' --no-recursion -T '.escapeshellarg($listFile).' 2>&1';
	exec($cmd, $tarOut, $tarRet);
	@unlink($listFile);
	if ($tarRet !== 0) {
		@unlink($packFile);
		return array('ok' => false, 'log' => 'Bundle FAILED: '.implode("\n", $tarOut), 'packfile' => '', 'count' => count($lines));
	}
	$size = @filesize($packFile);
	return array(
		'ok' => true,
		'log' => 'Bundle: '.$packFile.' ('.($size !== false ? $size : '?').' bytes, '.count($lines).' file(s))',
		'packfile' => $packFile,
		'count' => count($lines)
	);
}

/**
 * Return the basename + mtime of the latest existing bundle on disk.
 *
 * @return array array(basename|'', mtime|0)
 */
function slyPatchLatestBundle()
{
	$packDir = DOL_DATA_ROOT.'/slycustom/patch-backups/packs';
	if (!is_dir($packDir)) return array('', 0);
	$candidates = array();
	$dh = @opendir($packDir);
	if ($dh === false) return array('', 0);
	while (($f = readdir($dh)) !== false) {
		if (strpos($f, 'sly24.0-bundle_') === 0 && substr($f, -7) === '.tar.gz') {
			$full = $packDir.'/'.$f;
			if (is_file($full)) {
				$candidates[$f] = filemtime($full);
			}
		}
	}
	closedir($dh);
	if (empty($candidates)) return array('', 0);
	arsort($candidates);
	$first = array_key_first($candidates);
	return array($first, $candidates[$first]);
}

