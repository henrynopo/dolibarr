-- ============================================================
-- SGPayroll 升级脚本 v1.6
-- 包含：
--   1. 法定税率配置表 (llx_sgpayroll_statutory_rates)
--   2. 2027年CPF费率变动（仅变动的记录）
--
-- 2024年为完整基准费率（OW ceiling $6,800）
-- 2025年变动：OW ceiling变为$7,400
-- 2026年变动：SC 55-60岁费率调整
-- 2027年变动：SC 55-65岁费率调整（仅插入变动记录）
--
-- ============================================================
-- 【数据维护约定】  CPF 费率表累计写法
-- ============================================================
--   基准 (baseline)  写在  llx_sgpayroll_cpfrates.sql
--   后续年份 (2025+)  只写「相对上一年的变动」—— 不重写未变的记录
--
--   原因（2026-07-30 与用户确认）：
--     1. 减少 sql 体积与升级时间
--     2. CPF 系统会按 effective_date 查最新生效记录；
--        未变的记录由前一年的数据自然覆盖，无需重复插入
--     3. 2025 年只补 OW ceiling 变化 $7,400 → $8,000
--        2026 年只补 SC 55-65 段 Senior Worker 调整
--        2027 年只补 SC/PR3Y 55-65 段调整
--        未变的 SC <=55 / PR1Y / PR2Y 等不动
--
--   每年升级脚本命名约定：
--     llx_sgpayroll_upgrade_16a.sql  ← 2027 变动
--     llx_sgpayroll_upgrade_17a.sql  ← 2028 变动（如需）
--     llx_sgpayroll_upgrade_18a.sql  ← 2029 变动（如需）
--     编号顺序递增，每份只写 delta
--
--   禁止：
--     - 重写前一年的完整数据（除非 CPF Board 正式回调）
--     - 在 upgrade_*.sql 里 DELETE 已有记录（高风险，必须先和用户确认）
-- ============================================================

-- ============================================================
-- 1. 创建法定税率配置表
-- ============================================================
CREATE TABLE IF NOT EXISTS llx_sgpayroll_statutory_rates (
    rowid             INT           NOT NULL AUTO_INCREMENT PRIMARY KEY,
    rate_type         VARCHAR(30)   NOT NULL COMMENT 'SDL|SDL_CEILING|SDL_MIN|SDL_MAX|SHG_CDAC|SHG_ECF|SHG_MBMF|SHG_SINDA',
    effective_date    DATE          NOT NULL COMMENT 'Rate effective from this date',
    rate_value        DECIMAL(10,4) NOT NULL DEFAULT 0 COMMENT 'Percentage (e.g. 0.25 = 0.25%) or fixed amount',
    ceiling           DECIMAL(12,2) DEFAULT 0 COMMENT 'Wage ceiling for percentage-based rates',
    min_amount        DECIMAL(10,2) DEFAULT 0 COMMENT 'Minimum levy amount',
    max_amount        DECIMAL(10,2) DEFAULT 0 COMMENT 'Maximum levy amount',
    wage_band         VARCHAR(20)   DEFAULT '' COMMENT 'For SHG fixed amounts: wage bracket key',
    note              VARCHAR(255)  DEFAULT '',
    tms               TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uq_statutory (rate_type, effective_date, wage_band)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

